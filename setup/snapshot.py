"""Snapshot of everything outside the Python code that AutoEdit depends on: Claude skills/plugins, ComfyUI models and
custom nodes, Resolve add-ons and LUT folders. Writes setup/toolchain.json; setup/install.ps1 restores from it.
Own files (skills, the Auto Grade script) live in the repo; bought packs are only listed with a hash (public repo).
usage: python setup/snapshot.py        (re-run after adding a skill, plugin, pack or model, then commit)"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
HOME = Path.home()
CLAUDE = HOME / ".claude"
COMFY = Path(os.environ.get("LOCALAPPDATA", "")) / "Comfy-Desktop" / "ComfyUI-Shared"
FUSION = Path(os.environ.get("APPDATA", "")) / "Blackmagic Design" / "DaVinci Resolve" / "Support" / "Fusion"
LUT = Path(r"C:\ProgramData\Blackmagic Design\DaVinci Resolve\Support\LUT")
# LUT folders that do not come with Resolve: generated by autoedit/grade.py, or bought / exported by Timon
LUT_EXTRA = {"AutoEdit": "generated by autoedit/grade.py (rebuilt on first grade)",
             "FOUR Editors": "bought pack (FOUR Editors) - restore from your own backup",
             "Powergrade LUTS": "Timon's PowerGrade LUTs - restore from your own backup"}
HF = "https://huggingface.co/Comfy-Org"
MODEL_URLS = {
    "diffusion_models/wan2.2_ti2v_5B_fp16.safetensors":
        f"{HF}/Wan_2.2_ComfyUI_Repackaged/resolve/main/split_files/diffusion_models/wan2.2_ti2v_5B_fp16.safetensors",
    "vae/wan2.2_vae.safetensors": f"{HF}/Wan_2.2_ComfyUI_Repackaged/resolve/main/split_files/vae/wan2.2_vae.safetensors",
    "text_encoders/umt5_xxl_fp8_e4m3fn_scaled.safetensors":
        f"{HF}/Wan_2.1_ComfyUI_repackaged/resolve/main/split_files/text_encoders/umt5_xxl_fp8_e4m3fn_scaled.safetensors",
}


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def tree_hash(root: Path) -> tuple[int, str]:
    """(file count, sha256 over relative paths + file hashes) of a folder."""
    h, n = hashlib.sha256(), 0
    for p in sorted(x for x in root.rglob("*") if x.is_file()):
        h.update(f"{p.relative_to(root).as_posix()}:{sha256(p)}\n".encode())
        n += 1
    return n, h.hexdigest()


def load(p: Path) -> dict:
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def claude() -> dict:
    repo_skills = sorted(p.parent.name for p in (REPO / ".claude" / "skills").glob("*/SKILL.md"))
    user_skills = sorted(p.parent.name for p in (CLAUDE / "skills").glob("*/SKILL.md"))
    return {
        "skills_in_repo": repo_skills,                     # .claude/skills/<name>, install.ps1 copies them to ~/.claude/skills
        "user_skills_not_in_repo": [s for s in user_skills if s not in repo_skills],
        "marketplaces": {k: v.get("source") for k, v in load(CLAUDE / "plugins" / "known_marketplaces.json").items()},
        "installed_plugins": sorted(load(CLAUDE / "plugins" / "installed_plugins.json").get("plugins", {})),
        "enabled_plugins": load(CLAUDE / "settings.json").get("enabledPlugins", {}),
        "account_provided": ["anthropic-skills (built in to Claude)", "productivity (claude.ai plugin catalog, follows your account)"],
    }


def comfy() -> dict:
    models = {}
    for rel, url in MODEL_URLS.items():
        p = COMFY / "models" / rel
        models[rel] = {"url": url, "bytes": p.stat().st_size if p.exists() else None}
    nodes = sorted(p.name for p in (COMFY / "custom_nodes").iterdir() if p.is_dir() and not p.name.startswith("__")) \
        if (COMFY / "custom_nodes").exists() else []
    return {"app": "Comfy Desktop (comfy.org/download)", "base": "%LOCALAPPDATA%/Comfy-Desktop/ComfyUI-Shared",
            "models": models, "custom_nodes": nodes}


def resolve() -> dict:
    templates = {p.name: {"bytes": p.stat().st_size, "sha256": sha256(p)}
                 for p in sorted((FUSION / "Templates").glob("*.drfx"))}
    loose = sorted({p.parent.relative_to(FUSION / "Templates").as_posix()
                    for p in (FUSION / "Templates").rglob("*.setting")})
    scripts = sorted(p.relative_to(FUSION / "Scripts").as_posix() for p in (FUSION / "Scripts").rglob("*") if p.is_file())
    luts = {}
    for name, note in LUT_EXTRA.items():
        if (LUT / name).exists():
            n, h = tree_hash(LUT / name)
            luts[name] = {"files": n, "sha256": h, "note": note}
    return {"drfx_packs": templates, "loose_template_folders": loose, "scripts": scripts,
            "scripts_in_repo": sorted(p.relative_to(REPO / "setup" / "resolve" / "Scripts").as_posix()
                                      for p in (REPO / "setup" / "resolve" / "Scripts").rglob("*") if p.is_file()),
            "lut_folders": luts}


if __name__ == "__main__":
    out = REPO / "setup" / "toolchain.json"
    data = {"claude": claude(), "comfy": comfy(), "resolve": resolve()}
    out.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    print(json.dumps({k: {kk: (len(vv) if isinstance(vv, (list, dict)) else vv) for kk, vv in v.items()}
                      for k, v in data.items()}, indent=1))
